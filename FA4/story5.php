    <h2>The Yellow Wallpaper</h2>
    <p>It is very seldom that mere ordinary people like John and myself secure ancestral halls for the summer.</p>
    <p>A colonial mansion, a hereditary estate, I would say a haunted house, and reach the height of romantic felicity—but that would be asking too much of fate!</p>
    <p>Still I will proudly declare that there is something queer about it.</p>
    <p>Else, why should it be let so cheaply? And why have stood so long untenanted?</p>
    <p>John laughs at me, of course, but one expects that in marriage.</p>
    <p>John is practical in the extreme. He has no patience with faith, an intense horror of superstition, and he scoffs openly at any talk of things not to be felt and seen and put down in figures.</p>
    <p>John is a physician, and perhaps—(I would not say it to a living soul, of course, but this is dead paper and a great relief to my mind)—perhaps that is one reason I do not get well faster.</p>
    <p>You see, he does not believe I am sick!</p>
    <p>And what can one do?</p>
    <p>If a physician of high standing, and one’s own husband, assures friends and relatives that there is really nothing the matter with one but temporary nervous depression—a slight hysterical tendency—what is one to do?</p>
    <p>My brother is also a physician, and also of high standing, and he says the same thing.</p>
    <p>So I take phosphates or phosphites—whichever it is, and tonics, and journeys, and air, and exercise, and am absolutely forbidden to “work” until I am well again.</p>
    <p>Personally, I disagree with their ideas.</p>
    <p>Personally, I believe that congenial work, with excitement and change, would do me good.</p>
    <p>But what is one to do?</p>
    <p>I did write for a while in spite of them; but it does exhaust me a good deal—having to be so sly about it, or else meet with heavy opposition.</p>
    <p>I sometimes fancy that in my condition if I had less opposition and more society and stimulus—but John says the very worst thing I can do is to think about my condition, and I confess it always makes me feel bad.</p>
    <p>So I will let it alone and talk about the house.</p>
    <p>The most beautiful place! It is quite alone, standing well back from the road, quite three miles from the village. It makes me think of English places that you read about, for there are hedges and walls and gates that lock, and lots of separate little houses for the gardeners and people.</p>
    <p>There is a delicious garden! I never saw such a garden—large and shady, full of box-bordered paths, and lined with long grape-covered arbors with seats under them.</p>

